_PACK_GRADES = None


def _short(label):
    """'5-класс' -> '5-кл.', '5–6' -> '5–6 кл.', '2–3 кл.' stays."""
    label = label.strip()
    if label.endswith('-класс'):
        return label[:-len('класс')] + 'кл.'
    if label.endswith('кл.'):
        return label
    return f'{label}-кл.' if label.isdigit() else f'{label} кл.'


def _pack_grades():
    from apps.resources.data.pack_pages import PATH_PAGES, SLUG_PAGES, page_for
    from apps.resources.data.spiral import grade_label
    grades = {}
    for slug in SLUG_PAGES:
        grades[f'/{slug}/'] = grade_label(page_for(slug, ''))
    for key in PATH_PAGES:
        grades['/resources/topic/' + '/'.join(key) + '/'] = grade_label(page_for(key, ''))
    return grades


def grade_for_url(url):
    """The short grade label for a menu link ('5-кл.', '5–6 кл.'), or ''."""
    global _PACK_GRADES
    if _PACK_GRADES is None:
        _PACK_GRADES = _pack_grades()
    label = _PACK_GRADES.get(url) or AUDIT_GRADES.get(url)
    return _short(label) if label else ''
